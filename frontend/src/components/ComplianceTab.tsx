import { Fragment, useState } from 'react'
import { Link } from 'react-router-dom'
import { api, type ApplicationDetail, type RuleResult, type Run } from '../api'
import { fmtDate, fmtDateTime, humanize, useApi } from '../util'
import { Badge, Empty, ErrorBox, Loading } from './ui'

const ICON: Record<string, [string, string]> = {
  PASS: ['✓', 'success'], FAIL: ['×', 'critical'], WARN: ['!', 'warning'], PENDING: ['○', 'info'],
  DISABLED: ['–', 'muted'], ERROR: ['?', 'critical'],
}
const GROUP_ORDER = ['DOCUMENT', 'EXPIRY', 'CONSISTENCY', 'REGULATORY', 'ANOMALY', 'VERIFICATION', 'INFRASTRUCTURE']

export default function ComplianceTab({ app, version, onOpenFinding }: { app: ApplicationDetail; version: number; onOpenFinding: (id: number) => void }) {
  const { data, error, loading, reload } = useApi(
    () => api.get<{ run: Run | null; results: RuleResult[] }>(`/applications/${app.id}/compliance`), [app.id, version])
  const [open, setOpen] = useState<string | null>(null)

  if (loading && !data) return <Loading />
  if (error) return <ErrorBox error={error} onRetry={reload} />
  if (!data?.run) return <Empty>The checklist is generated by AI pre-scrutiny. Run it from the application header.</Empty>

  const results = data.results
  const evaluated = results.filter(r => r.outcome !== 'DISABLED')
  const passed = evaluated.filter(r => r.outcome === 'PASS').length
  const groups = GROUP_ORDER.map(g => ({ g, items: results.filter(r => r.group === g) })).filter(x => x.items.length)

  return (
    <div style={{ marginTop: 20 }}>
      <div className="row wrap" style={{ marginBottom: 14 }}>
        <div><b className="nums" style={{ fontSize: 16 }}>{passed} / {evaluated.length}</b> <span className="muted">requirements satisfied</span></div>
        <span className="spacer" />
        <span className="faint" style={{ fontSize: 12 }}>
          {app.category_label} checklist · run #{data.run.id} · {fmtDateTime(data.run.finished_at)} · evaluation date {fmtDate(data.run.reference_date)}
        </span>
        <Link to="/rules" style={{ fontSize: 13 }}>Configure rules →</Link>
      </div>
      <div className="table-wrap">
        {groups.map(({ g, items }) => (
          <Fragment key={g}>
            <div className="group-head"><span>{humanize(g)}</span><span>{items.filter(i => i.outcome === 'PASS').length}/{items.filter(i => i.outcome !== 'DISABLED').length} passed</span></div>
            {items.map(r => {
              const [icon, tone] = ICON[r.outcome] || ['?', 'muted']
              const exp = open === r.rule_id
              return (
                <Fragment key={r.rule_id}>
                  <button className="compliance-row" onClick={() => setOpen(exp ? null : r.rule_id)} aria-expanded={exp}>
                    <span className={`compliance-icon tone-${tone}`}>{icon}</span>
                    <span style={{ flex: 1, minWidth: 0 }}>
                      <span style={{ fontWeight: 500 }}>{r.rule_name}</span>
                      <span className="muted" style={{ marginLeft: 10, fontSize: 13 }}>{r.message}</span>
                    </span>
                    <span className="faint mono">{r.rule_id} · v{r.rule_version}</span>
                    <Badge value={r.outcome} />
                  </button>
                  {exp && (
                    <div className="compliance-expanded">
                      <div><div className="kv-label">Result</div><div className="kv-value">{r.message}</div></div>
                      <div><div className="kv-label">Rule</div><div className="kv-value">{r.rule_id} (version {r.rule_version}) · default severity {humanize(r.severity)}</div></div>
                      <div><div className="kv-label">Evidence checked</div><div className="kv-value">
                        {r.evidence?.length ? r.evidence.slice(0, 6).map((e, i) => <div key={i}>{e.label}{e.page ? ` · p.${e.page}` : ''}{e.value && e.kind !== 'document' ? ` — ${e.value}` : ''}</div>) : '—'}
                      </div></div>
                      <div><div className="kv-label">Findings</div><div className="kv-value">
                        {r.finding_ids.length ? r.finding_ids.map(id => (
                          <div key={id}><button className="btn btn-ghost btn-sm" style={{ padding: 0 }} onClick={() => onOpenFinding(id)}>Open finding #{id} →</button></div>
                        )) : 'None'}
                      </div></div>
                      <div><div className="kv-label">Last evaluated</div><div className="kv-value">{fmtDateTime(r.evaluated_at)}</div></div>
                    </div>
                  )}
                </Fragment>
              )
            })}
          </Fragment>
        ))}
      </div>
    </div>
  )
}
